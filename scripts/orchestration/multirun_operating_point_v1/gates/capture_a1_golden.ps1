        unmanaged_note = 'The certified arms set ONLY the seven names above. Seeds (MULTIRUN_BASE_SEED/SEED_OFFSET), stores (MULTIRUN_STORE_PARENT), CUDA_DEVICE_ORDER, and every mode knob were left to the ambient environment, whose cleanliness the campaign verified through its ambient-preauthorization machinery (ambient-preauthorized-set.json per arm).'
    }
    v1_divergences = @(
        [ordered]@{
            names = @('CUDA_VISIBLE_DEVICES', 'MTG_KERNEL_PILOT_CUDA_ORDINAL', 'CUDA_DEVICE_ORDER')
            certified = 'CUDA_VISIBLE_DEVICES cleared; placement via MTG_KERNEL_PILOT_CUDA_ORDINAL = device ordinal; CUDA_DEVICE_ORDER unmanaged'
            v1 = 'CUDA_VISIBLE_DEVICES = pinned device UUID; MTG_KERNEL_PILOT_CUDA_ORDINAL always 0; CUDA_DEVICE_ORDER = PCI_BUS_ID'
            justification = 'The bridge ordinal parse is lenient (absent/unparsable silently means 0, bridge.rs:418-425): under certified-style placement a typo stacks every process on device 0. UUID masking pins device identity in-record and makes the lenient parse unreachable. Placement mechanism changes; run semantics do not. Gate A3 (store byte-identity) and both confirmation legs validate on-device equivalence.'
        },
        [ordered]@{
            names = @('MULTIRUN_BASE_SEED', 'MULTIRUN_SEED_OFFSET')
            certified = 'unset; both device processes fell to pilot defaults (base 424242, offset 0), so cross-process run seeds overlapped, harmless for ephemeral throughput arms'
            v1 = 'explicit base_seed from config plus cumulative per-process offsets (the S1-proven scheme), collision-free by construction'
            justification = 'v1 runs durable stores; overlapping run seeds across processes would be a correctness defect there.'
        },
        [ordered]@{
            names = @('MULTIRUN_STORE_PARENT')
            certified = 'unset; ephemeral per-run stores'
            v1 = 'explicit fresh-root durable parent per process'
            justification = 'Productized launches keep stores for post-run validation and eps/s recomputation.'
        },
        [ordered]@{
            names = @('all mode knobs and MULTIRUN_EXECUTION_MODE')
            certified = 'unmanaged, relied on verified-clean ambient environment'
