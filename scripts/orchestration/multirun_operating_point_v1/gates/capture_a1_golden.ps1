# Gate A1 golden capture harness. Derives the golden fixture from the
# CERTIFIED fair-campaign records (the winning 2026-07-24 attempt 5 run),
# never from hand-authored values: the archived runner copy is SHA-verified
# against campaign-complete.json, its env-construction block is extracted by
# anchored regex (fail-closed on any shape drift), and the parameter values
# come from the pilot's own printed CONFIG lines in the certified device
# logs. Rerunning this script must reproduce the committed fixture
# byte-for-byte; the reproducibility gate in run_cold_gates.ps1 asserts it.
param(
    [string]$ArtifactDir = 'C:\Users\Jack\IdeaProjects\mtg-kernel-fair-campaign-harness-fable\artifacts\fair-sparse-campaign\20260724T1647536950174Z-fair-sparse-f31-b31-f32-6f53c1e58af1',
    [string]$OutputPath = (Join-Path $PSScriptRoot 'a1-golden-legacy-env.json')
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

# Pinned identity of the certified run (TO-CODEX.md 2026-07-24 14:15 entry).
$expectedCampaignCompleteSha = 'aa6034060597e782c1e2415af103cf333afc04c62bce9ebec5171331eec69173'

function Get-Sha256HexLocal { param([string]$Path)
    return (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash.ToLowerInvariant()
}

$campaignCompletePath = Join-Path $ArtifactDir 'campaign-complete.json'
$runnerCopyPath = Join-Path $ArtifactDir '00-runner-starting-copy.ps1'
foreach ($required in @($campaignCompletePath, $runnerCopyPath)) {
    if (-not (Test-Path -LiteralPath $required)) { throw "certified artifact missing: $required" }
}
$campaignCompleteSha = Get-Sha256HexLocal -Path $campaignCompletePath
if ($campaignCompleteSha -cne $expectedCampaignCompleteSha) {
    throw "campaign-complete.json sha $campaignCompleteSha does not match the pinned certified identity"
}
$campaignComplete = Get-Content -LiteralPath $campaignCompletePath -Raw | ConvertFrom-Json
$runnerCopySha = Get-Sha256HexLocal -Path $runnerCopyPath
if ($runnerCopySha -cne $campaignComplete.runner_starting_sha256.ToLowerInvariant()) {
    throw 'archived runner copy sha does not match campaign-complete.json runner_starting_sha256'
}

# Extract the env-construction block from the SHA-verified runner copy.
# Anchored to the exact assignment shape; any drift fails closed.
$runnerText = Get-Content -LiteralPath $runnerCopyPath -Raw
$envBlockPattern = '(?s)CUDA_VISIBLE_DEVICES = \$null\s*' +
    'MULTIRUN_RUNS = \$definition\.runs\.ToString\(\)\s*' +
    'MULTIRUN_UPDATES = \$ExpectedUpdates\.ToString\(\)\s*' +
    'MULTIRUN_WORKERS = \$ExpectedWorkers\.ToString\(\)\s*' +
    'MULTIRUN_SESSIONS = \$ExpectedSessions\.ToString\(\)\s*' +
    'MULTIRUN_BROKER_TARGET = \$ExpectedBrokerTarget\.ToString\(\)\s*' +
    'MTG_KERNEL_PILOT_CUDA_ORDINAL = \$definition\.ordinal\.ToString\(\)'
if ($runnerText -cnotmatch $envBlockPattern) {
    throw 'archived runner env-construction block does not match the anchored expected shape'
}

# Pilot-printed CONFIG lines from the certified device logs: the running
# binary's self-reported parameters, the strongest available record. Every
# log is hash-verified against campaign-complete.json's recorded
# device_results[].validation.stdout_sha256 BEFORE any line is trusted.
$configLinePattern = 'MULTIRUN CONFIG runs=(\d+) updates=(\d+) topology=(\d+)x(\d+) broker_target=(\d+)'
$configLines = [ordered]@{}
$logHashes = [ordered]@{}
foreach ($probe in @(
    @{ arm = 'F31'; device = 0 }, @{ arm = 'F31'; device = 1 },
    @{ arm = 'F32'; device = 0 }, @{ arm = 'F32'; device = 1 }
)) {
    $logPath = Join-Path $ArtifactDir ("{0}\device{1}.stdout.log" -f $probe.arm, $probe.device)
    $armEntry = @($campaignComplete.arm_results | Where-Object { $_.arm -ceq $probe.arm })
    if ($armEntry.Count -ne 1) { throw "expected exactly one arm_results entry for $($probe.arm)" }
    $deviceEntry = @($armEntry[0].device_results | Where-Object { $_.device_ordinal -eq $probe.device })
    if ($deviceEntry.Count -ne 1) { throw "expected exactly one device_results entry for $($probe.arm) device $($probe.device)" }
    $recordedSha = $deviceEntry[0].validation.stdout_sha256.ToLowerInvariant()
    $actualSha = Get-Sha256HexLocal -Path $logPath
    if ($actualSha -cne $recordedSha) { throw "device log $logPath sha $actualSha does not match the recorded certified hash $recordedSha" }
    $key = "{0}_device{1}" -f $probe.arm.ToLowerInvariant(), $probe.device
    $logHashes[$key] = $actualSha
    $line = (Select-String -LiteralPath $logPath -Pattern $configLinePattern | Select-Object -First 1)
    if ($null -eq $line) { throw "no CONFIG line in $logPath" }
    $configLines[$key] = $line.Line.Trim()
    if ($line.Line -cnotmatch 'updates=64 topology=2x32 broker_target=16') {
        throw "certified CONFIG line in $logPath does not carry the expected 64/2x32/16 parameters"
    }
}

$fixture = [ordered]@{
