#[test]
fn retained_numeric_pilot_leg_zero_encodes_the_original_pilfer_menu() {
    let mut owner = reset_pilot(PlayerSeatV1::P0);
    assert_eq!(ORDINALS.len(), 653 * 5);
    replay_pilot_prefix(&mut owner, ORDINALS, usize::MAX);

    let native = owner.fixture_state();
    assert!(native.engine.halted.is_none());
    let pending = native
        .engine
        .pending_effect
        .as_ref()
        .expect("resolving Pilfer");
    assert_eq!(
        CARD_DEFS[usize::from(native.objects.get(pending.ctx.source).card_def)].name,
        "Pilfer"
    );
    assert_eq!(pending.ctx.controller, PlayerId::P1);
    assert_eq!(pending.ctx.targets, [Target::Player(PlayerId::P0)]);

    let FastActorResponseV1::Decision(expected) = owner.current_response() else {
        panic!("pilot ended before Pilfer: {:?}", owner.current_response());
    };
    assert_eq!(expected.step, 653);
    assert_eq!(expected.acting_player, PlayerSeatV1::P1);
    assert_eq!(expected.decision_kind, FastActorDecisionKindV1::Surface);
    let bound = owner.encode(expected).unwrap_or_else(|error| {
        panic!(
            "pilot Pilfer projection: {error:?}; {:?}",
            owner.fixture_projection_error()
        )
    });
    let actions = bound.fixture_backend_v75().actions();
    assert_eq!(actions.len(), 5);
    assert!(actions.iter().all(|action| matches!(action,
        Action::ChooseEffectTarget { target: TargetRefV1::Object { object }, .. }
            if object.owner == PlayerSeatV1::P0 && object.zone == Zone::Hand
    )));
    assert_eq!(bound.packet().actions().len(), 5);
}
