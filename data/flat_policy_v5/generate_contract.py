"""Generate or check only the explicit Flat V5 / Python V8 feature pins."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "python"))
from mtg_kernel_rl import features_v8 as features


def generate(*, check: bool = False) -> None:
    directory = Path(__file__).resolve().parent
    source_hash = hashlib.sha256(Path(features.__file__).read_bytes()).hexdigest()
    descriptor = {
        "schema": "flat-policy-v5-feature-contract-1",
        "rich_observation_schema": 8,
        "legal_action_schema": 5,
        "feature_schema_version": features.FEATURE_SCHEMA_VERSION,
        "feature_registry_version": features.FEATURE_REGISTRY_VERSION,
        "feature_contract_digest": features.feature_contract_fingerprint(),
        "feature_encoding_digest": features.encoding_contract_fingerprint(),
        "features_source_path": "python/mtg_kernel_rl/features_v8.py",
        "features_source_sha256": source_hash,
        "model_contract_version": features.MODEL_CONTRACT_VERSION,
        "dimensions": {
            "state": features.STATE_FEATURE_DIM,
            "object": features.OBJECT_FEATURE_DIM,
            "edge": features.EDGE_FEATURE_DIM,
            "action": features.ACTION_FEATURE_DIM,
            "action_ref": features.ACTION_REF_FEATURE_DIM,
            "object_groups": len(features.OBJECT_GROUPS),
        },
        "encoding": features.EXTENSION_ENCODING_CONTRACT_V8,
        "extension_edge_subroles": {
            "cost_source": 32, "cost_selected": 33, "search_card": 34,
            "historical_source": 35, "pending_ward_payment": 36, "queued_ward_payment": 37,
            "pending_ward_life_payment": 38, "queued_ward_life_payment": 39, "ward_life_card_trait": 40,
        },
        "provenance_boundary": "Python validates internal consistency; authoritative Rust production validates actual public history and hidden-state scope.",
        "admission": "Prepared feature authority. Rust FlatPolicyV5/native V5, exact parity, fresh model identity and actual Sire gameplay remain separately required.",
        "transfer": "Identical numeric dimensions do not admit predecessor checkpoints or establish learned competence. Explicitly labeled transfer requires separate authority.",
    }
    descriptor_bytes = (json.dumps(descriptor, sort_keys=True, indent=2, ensure_ascii=False) + "\n").encode()
    values = {
        "FEATURE_SCHEMA_VERSION_V5": features.FEATURE_SCHEMA_VERSION,
        "FEATURE_REGISTRY_VERSION_V5": features.FEATURE_REGISTRY_VERSION,
        "FEATURE_CONTRACT_DIGEST_V5": features.feature_contract_fingerprint(),
        "FEATURE_ENCODING_DIGEST_V5": features.encoding_contract_fingerprint(),
        "FEATURES_SOURCE_SHA256_V5": source_hash,
        "MODEL_CONTRACT_VERSION_V5": features.MODEL_CONTRACT_VERSION,
        "FEATURE_DESCRIPTOR_SHA256_V5": hashlib.sha256(descriptor_bytes).hexdigest(),
    }
    lines = ["// Generated by data/flat_policy_v5/generate_contract.py. Predecessor pins remain separate."]
    lines.extend(f'pub(crate) const {key}: &str = "{value}";' for key, value in values.items())
    outputs = {
        directory / "feature_contract_v5.json": descriptor_bytes,
        directory / "feature_identity.rs": ("\n".join(lines) + "\n").encode(),
    }
    for path, expected in outputs.items():
        if check:
            if not path.exists() or path.read_bytes() != expected:
                raise SystemExit(f"Generated successor pin differs: {path}")
        else:
            path.write_bytes(expected)
    print(json.dumps(values, sort_keys=True))


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    generate(check=parser.parse_args().check)
