"""Generate explicit V9 feature pins for the prospective native V6 consumer."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "python"))
from mtg_kernel_rl import features_v9 as features


def generate(*, check: bool = False) -> None:
    directory = Path(__file__).resolve().parent
    predecessor = features.predecessor
    source_hash = hashlib.sha256(Path(features.__file__).read_bytes()).hexdigest()
    descriptor = {
        "schema": "flat-policy-v6-feature-contract-1",
        "rich_observation_schema": 9,
        "legal_action_schema": 5,
        "feature_schema_version": features.FEATURE_SCHEMA_VERSION,
        "feature_registry_version": features.FEATURE_REGISTRY_VERSION,
        "feature_contract_digest": features.feature_contract_fingerprint(),
        "feature_encoding_digest": features.encoding_contract_fingerprint(),
        "features_source_path": "python/mtg_kernel_rl/features_v9.py",
        "features_source_sha256": source_hash,
        "predecessor_source_sha256": hashlib.sha256(Path(predecessor.__file__).read_bytes()).hexdigest(),
        "predecessor_feature_contract_digest": predecessor.feature_contract_fingerprint(),
        "predecessor_encoding_digest": predecessor.encoding_contract_fingerprint(),
        "model_contract_version": features.MODEL_CONTRACT_VERSION,
        "dimensions": {"state": features.STATE_FEATURE_DIM,
                       "object": predecessor.OBJECT_FEATURE_DIM,
                       "edge": predecessor.EDGE_FEATURE_DIM,
                       "action": predecessor.ACTION_FEATURE_DIM,
                       "action_ref": predecessor.ACTION_REF_FEATURE_DIM,
                       "object_groups": len(predecessor.OBJECT_GROUPS)},
        "state_prefix": "unchanged V8 state tensor",
        "state_suffix": ["actor_attacked_this_turn", "opponent_attacked_this_turn"],
        "other_tensors": "unchanged V8",
        "provenance_boundary": "Engine producer authenticates public declaration history; Python checks JSON consistency.",
        "admission": "Prepared pins. Typed native binding, Human consumer and actual cross-consumer parity remain required. No model or training runtime admission.",
    }
    raw = (json.dumps(descriptor, sort_keys=True, indent=2, ensure_ascii=False) + "\n").encode("utf-8")
    values = {"FEATURE_SCHEMA_VERSION_V6": features.FEATURE_SCHEMA_VERSION,
              "FEATURE_REGISTRY_VERSION_V6": features.FEATURE_REGISTRY_VERSION,
              "FEATURE_CONTRACT_DIGEST_V6": features.feature_contract_fingerprint(),
              "FEATURE_ENCODING_DIGEST_V6": features.encoding_contract_fingerprint(),
              "FEATURES_SOURCE_SHA256_V6": source_hash,
              "MODEL_CONTRACT_VERSION_V6": features.MODEL_CONTRACT_VERSION,
              "FEATURE_DESCRIPTOR_SHA256_V6": hashlib.sha256(raw).hexdigest()}
    lines = ["// Generated by data/flat_policy_v6/generate_contract.py."]
    lines.extend(f'pub(crate) const {key}: &str = "{value}";' for key, value in values.items())
    outputs = {directory / "feature_contract_v6.json": raw,
               directory / "feature_identity.rs": ("\n".join(lines) + "\n").encode("utf-8")}
    for path, expected in outputs.items():
        if check:
            if not path.exists() or path.read_bytes() != expected:
                raise SystemExit(f"Generated successor pin differs: {path}")
        else:
            path.write_bytes(expected)
    print(json.dumps(values, sort_keys=True))


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    generate(check=parser.parse_args().check)
