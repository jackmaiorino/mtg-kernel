"""Regenerate only the FlatV8 (V8 inclusion contract) feature pins from features_v11.py."""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "python"))
from mtg_kernel_rl import features_v11 as features


def generate() -> None:
    directory = Path(__file__).resolve().parent
    source_hash = hashlib.sha256(Path(features.__file__).read_bytes()).hexdigest()
    descriptor = {
        "schema": "flat-policy-v8-feature-contract-1",
        "rich_observation_schema": 7,
        "legal_action_schema": 5,
        "feature_schema_version": features.FEATURE_SCHEMA_VERSION,
        "feature_registry_version": features.FEATURE_REGISTRY_VERSION,
        "feature_contract_digest": features.feature_contract_fingerprint(),
        "feature_encoding_digest": features.encoding_contract_fingerprint(),
        "features_source_path": "python/mtg_kernel_rl/features_v11.py",
        "features_source_sha256": source_hash,
        "predecessor_features_source_path": "python/mtg_kernel_rl/features_v10.py",
        "model_contract_version": features.MODEL_CONTRACT_VERSION,
        "dimensions": {"state": 219, "object": 98, "edge": 41, "action": 196, "action_ref": 25, "object_groups": 20},
        "additions": {
            "include_column_195": "1.0 on the include:true row of an attacker- or blocker-inclusion decision, else 0.0",
            "pairing_node_indices": "(blocker node, attacker node) per block already chosen in the pending blocker declaration",
        },
        "design": "collab LANES/w4-combat-20261030/DESIGN.md (v5.1), section 5: V8 inclusion contract",
        "transfer": "A FlatV7 (or V4) checkpoint converts to the V8 net by the function-preserving V8 conversion (zero include column, zero pairing output projection). Every other tensor equals FlatV7's.",
    }
    descriptor_bytes = (json.dumps(descriptor, sort_keys=True, indent=2, ensure_ascii=False) + "\n").encode()
    (directory / "feature_contract_v8.json").write_bytes(descriptor_bytes)
    values = {
        "FEATURE_SCHEMA_VERSION_V8": features.FEATURE_SCHEMA_VERSION,
        "FEATURE_REGISTRY_VERSION_V8": features.FEATURE_REGISTRY_VERSION,
        "FEATURE_CONTRACT_DIGEST_V8": features.feature_contract_fingerprint(),
        "FEATURE_ENCODING_DIGEST_V8": features.encoding_contract_fingerprint(),
        "FEATURES_SOURCE_SHA256_V8": source_hash,
        "FEATURE_DESCRIPTOR_SHA256_V8": hashlib.sha256(descriptor_bytes).hexdigest(),
    }
    lines = ["// Generated by data/flat_policy_v8/generate_contract.py. V7 and V4 pins are separate."]
    lines += [f'pub(crate) const {key}: &str = "{value}";' for key, value in values.items()]
    (directory / "feature_identity.rs").write_bytes(("\n".join(lines) + "\n").encode())
    print(json.dumps(values, sort_keys=True))


if __name__ == "__main__":
    generate()
