"""Regenerate only the FlatV7 (London pregame) feature pins from features_v10.py."""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "python"))
from mtg_kernel_rl import features_v10 as features


def generate() -> None:
    directory = Path(__file__).resolve().parent
    source_hash = hashlib.sha256(Path(features.__file__).read_bytes()).hexdigest()
    descriptor = {
        "schema": "flat-policy-v7-feature-contract-1",
        "rich_observation_schema": 7,
        "legal_action_schema": 5,
        "feature_schema_version": features.FEATURE_SCHEMA_VERSION,
        "feature_registry_version": features.FEATURE_REGISTRY_VERSION,
        "feature_contract_digest": features.feature_contract_fingerprint(),
        "feature_encoding_digest": features.encoding_contract_fingerprint(),
        "features_source_path": "python/mtg_kernel_rl/features_v10.py",
        "features_source_sha256": source_hash,
        "predecessor_features_source_path": "python/mtg_kernel_rl/features_v7.py",
        "model_contract_version": features.MODEL_CONTRACT_VERSION,
        "dimensions": {"state": 219, "object": 98, "edge": 41, "action": 195, "action_ref": 25, "object_groups": 20},
        "reused_columns": {
            "action_kind_15": "london_opening (V4 choose_effect_number; numeric choices are refused)",
            "engine_stage_slot_9": "london_pregame (V4 halted)",
            "has_lost_pregame": "self: opponent announced a mulligan this round; opponent: opponent has kept",
        },
        "design": "docs/design/pauper_london_mulligans_v1.md",
        "transfer": "V4 checkpoints transfer by the explicit same-shape V4-to-V7 transfer. In-game V7 tensors equal V4 tensors; only pregame rows are new.",
    }
    descriptor_bytes = (json.dumps(descriptor, sort_keys=True, indent=2, ensure_ascii=False) + "\n").encode()
    (directory / "feature_contract_v7.json").write_bytes(descriptor_bytes)
    values = {
        "FEATURE_SCHEMA_VERSION_V7": features.FEATURE_SCHEMA_VERSION,
        "FEATURE_REGISTRY_VERSION_V7": features.FEATURE_REGISTRY_VERSION,
        "FEATURE_CONTRACT_DIGEST_V7": features.feature_contract_fingerprint(),
        "FEATURE_ENCODING_DIGEST_V7": features.encoding_contract_fingerprint(),
        "FEATURES_SOURCE_SHA256_V7": source_hash,
        "FEATURE_DESCRIPTOR_SHA256_V7": hashlib.sha256(descriptor_bytes).hexdigest(),
    }
    lines = ["// Generated by data/flat_policy_v7/generate_contract.py. V4 pins are separate."]
    lines += [f'pub(crate) const {key}: &str = "{value}";' for key, value in values.items()]
    (directory / "feature_identity.rs").write_bytes(("\n".join(lines) + "\n").encode())
    print(json.dumps(values, sort_keys=True))


if __name__ == "__main__":
    generate()
